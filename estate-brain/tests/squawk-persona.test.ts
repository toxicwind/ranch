import { describe, expect, test } from "bun:test";
import { ensureKey, personaYaml, renderRunners } from "../src/actions";
import { validateRegistry } from "../src/registry";

const sample = {
  version: 1,
  default_sender: "ember",
  tokens: { squawk_feed: "~/.fleet-bus/squawk-relay/feed-token" },
  profiles: {
    coordinator: {
      identity: "coordinator",
      key: "coordinator",
      token: null,
      role: "coordinator",
      description: "Orchestrator",
      channels: ["fleet"],
    },
    relay: {
      identity: "relay",
      key: "relay",
      token: "squawk_feed",
      role: "relay",
      description: "Feed bridge",
      channels: ["fleet"],
    },
  },
};

describe("validateRegistry", () => {
  test("accepts a valid registry", () => {
    const parsed = validateRegistry(sample);
    expect(parsed.default_sender).toBe("ember");
    expect(Object.keys(parsed.profiles)).toEqual(["coordinator", "relay"]);
  });

  test("rejects an unknown key", () => {
    expect(() =>
      validateRegistry({
        ...sample,
        profiles: {
          coordinator: { ...sample.profiles.coordinator, bogus: 1 },
        },
      }),
    ).toThrow(/registry invalid/);
  });

  test("rejects a missing identity", () => {
    expect(() =>
      validateRegistry({
        ...sample,
        profiles: {
          bad: { key: "x", channels: [] },
        },
      }),
    ).toThrow(/registry invalid/);
  });
});

describe("personaYaml/renderRunners", () => {
  test("renders a profile block", () => {
    const reg = validateRegistry(sample);
    const block = personaYaml("coordinator", reg.profiles.coordinator);
    expect(block).toContain("identity: coordinator");
    expect(block).toContain("channels: [fleet]");
  });

  test("renders the full runners.yml header", () => {
    const reg = validateRegistry(sample);
    const out = renderRunners(reg);
    expect(out).toContain("# GENERATED by squawk-persona");
    expect(out).toContain("profiles:");
    expect(out).toContain("coordinator:");
  });

  test("escapes newlines and quotes in a template", () => {
    const reg = validateRegistry({
      ...sample,
      profiles: {
        ...sample.profiles,
        coordinator: {
          ...sample.profiles.coordinator,
          message_template: '[x] {t}\n\n{body} says "hi"',
        },
      },
    });
    const out = renderRunners(reg);
    expect(out).toContain(
      'message_template: "[x] {t}\\n\\n{body} says \\"hi\\""',
    );
  });
});

describe("ensureKey", () => {
  test("writes a 32-byte hex key", async () => {
    const dir = new URL("./fixtures/keys/", import.meta.url).pathname;
    const file = `${dir}test.key`;
    // cleanup any prior
    try {
      Bun.file(file);
      await Bun.$`rm -f ${file}`.quiet();
    } catch {}
    const msg = await ensureKey(file);
    expect(msg).toContain("key written");
    const body = await Bun.file(file).text();
    expect(body.trim().length).toBe(64);
  });

  test("is idempotent when the key already exists", async () => {
    const dir = new URL("./fixtures/keys/", import.meta.url).pathname;
    const file = `${dir}test.key`;
    await ensureKey(file);
    const msg = await ensureKey(file);
    expect(msg).toContain("key exists");
  });
});
