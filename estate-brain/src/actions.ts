/**
 * actions.ts — filesystem + runners.yml generation helpers, Bun-native.
 * I/O via Bun.file() / Bun.write(); entropy via Bun.CryptoHasher-freed global
 * crypto (getRandomValues). No `node:crypto`, no raw `node:fs` writes.
 */

import { dirname } from "node:path";
import type { Persona, Registry } from "./types";

function entropyHex(nBytes: number): string {
  const buf = new Uint8Array(nBytes);
  crypto.getRandomValues(buf);
  return [...buf].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/**
 * Ensure a persona's signing key exists (0600, dir 0700). Uses Bun.write —
 * atomic-ish, sets restrictive mode after. Returns a human message.
 */
export async function ensureKey(keyFilePath: string): Promise<string> {
  const existing = Bun.file(keyFilePath);
  if (await existing.exists()) return `key exists: ${keyFilePath}`;
  const dir = dirname(keyFilePath);
  await Bun.write(Bun.file("/dev/null"), "").catch(() => undefined); // warm nothing
  // Make the keys dir with restrictive perms.
  await Bun.$`mkdir -p ${dir}`.quiet();
  await Bun.$`chmod 700 ${dir}`.quiet();
  const body = `${entropyHex(32)}\n`;
  await Bun.write(keyFilePath, body);
  await Bun.$`chmod 600 ${keyFilePath}`.quiet();
  return `key written: ${keyFilePath} (0600)`;
}

function esc(s: string): string {
  return s.replaceAll(/[\r\n]/g, "\\n").replaceAll('"', '\\"');
}

/** Render one persona as a runners.yml profile block in squawk's shape. */
export function personaYaml(name: string, p: Persona): string {
  const desc = p.description.trim().replace(/\s+/g, " ");
  const lines = [
    `  ${name}:`,
    `    identity: ${p.identity}`,
    `    key: ${p.key}`,
    `    role: ${p.role}`,
  ];
  if (desc) {
    lines.push("    description: >", `      ${desc}`);
  } else {
    lines.push('    description: ""');
  }
  lines.push(`    channels: [${p.channels.join(", ")}]`);
  if (p.poll_interval !== undefined)
    lines.push(`    poll_interval: ${p.poll_interval}`);
  if (p.heartbeat !== undefined) lines.push(`    heartbeat: ${p.heartbeat}`);
  if (p.message_template)
    lines.push(`    message_template: "${esc(p.message_template)}"`);
  return lines.join("\n");
}

/** Render the full runners.yml file for squawk from the registry. */
export function renderRunners(reg: Registry): string {
  const head =
    "# GENERATED by squawk-persona from personas.yml (do not edit by hand).\n" +
    "# Regenerate with: squawk-persona gen-runners\n" +
    "version: 1\n\nprofiles:\n";
  const body = Object.entries(reg.profiles)
    .map(([name, p]) => personaYaml(name, p))
    .join("\n");
  return `${head + body}\n`;
}

function inheritedEnv(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(process.env)) {
    if (v !== undefined) out[k] = v;
  }
  return out;
}

/**
 * Build the persona's runtime env for external CLI invocation (corral/delend).
 * Returns a plain Record to pass as `env`. Never prints secrets.
 */
export function personaEnv(
  reg: Registry,
  name: string,
  keysDir: string,
): Record<string, string> {
  const p = reg.profiles[name];
  if (!p) throw new Error(`unknown persona '${name}'`);
  const key = p.key ?? p.identity;
  const tok = p.token ? reg.tokens[p.token] : undefined;
  const env: Record<string, string> = {
    FLEET_KEYS_DIR: keysDir,
    SQUAWK_SENDER: p.identity,
    SQUAWK_PERSONA_KEY: `${keysDir}/${key}.key`,
  };
  if (tok) env.SQUAWK_PERSONA_TOKEN = tok;
  return { ...inheritedEnv(), ...env };
}

/**
 * Run a Corral orchestration command as `persona`. Spawns `corral` with the
 * persona identity in its env. Corral is the multi-agent fleet orchestrator
 * (spawn / bid / manage) — running it under a persona means that persona can
 * drive the fleet.
 *
 * Resolves corral from CORRAL_BIN or the corral repo's `src/cli/index.ts`.
 */
export async function runCorral(
  reg: Registry,
  name: string,
  keysDir: string,
  corralBin: string,
  args: string[],
): Promise<{ status: number; stdout: string; stderr: string }> {
  const env = personaEnv(reg, name, keysDir);
  const p = Bun.spawn({
    cmd: [corralBin, ...args],
    env,
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr] = await Promise.all([
    new Response(p.stdout).text(),
    new Response(p.stderr).text(),
  ]);
  const status = await p.exited;
  return { status, stdout, stderr };
}

/**
 * Run a DelendAI shared-checkout-merge checkpoint as `persona`, via
 * `delend-quick` (the universal zero-friction helper) when available, else
 * `delendai work checkpoint`. This is how an agent pushes its work to main.
 */
export async function runCheckpoint(
  reg: Registry,
  name: string,
  keysDir: string,
  delendBin: string,
  message: string,
): Promise<{ status: number; stdout: string; stderr: string }> {
  const env = personaEnv(reg, name, keysDir);
  const p = Bun.spawn({
    cmd: [delendBin, "-m", message],
    env,
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr] = await Promise.all([
    new Response(p.stdout).text(),
    new Response(p.stderr).text(),
  ]);
  const status = await p.exited;
  return { status, stdout, stderr };
}
