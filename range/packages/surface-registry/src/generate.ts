/**
 * generate — the auto-compose generator.
 *
 * Reads the estate SSOTs, composes the surface manifest and writes the
 * committed artifacts:
 *
 *   - `src/generated/surfaces.json` — the machine-readable manifest;
 *   - `src/generated/surfaces.ts`   — the typed wrapper around it.
 *
 * The output is DETERMINISTIC: sorted everywhere, no timestamps, no random
 * ids. Running the generator twice on an unchanged estate produces
 * byte-identical files, which is what makes `drift.ts` a usable gate.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { composeManifest, manifestToJson } from './compose.ts'
import { DEFAULT_ESTATE_ROOT, readEstateSources } from './estate.ts'
import { type SurfaceManifest } from './manifest.ts'

export const GENERATED_DIR_NAME = 'generated'
export const MANIFEST_JSON_NAME = 'surfaces.json'
export const MANIFEST_TS_NAME = 'surfaces.ts'

/** The directory the generated artifacts live in. */
export function defaultOutDir(): string {
  return join(dirname(fileURLToPath(import.meta.url)), GENERATED_DIR_NAME)
}

export interface GenerateOptions {
  readonly estateRoot?: string
  readonly outDir?: string
}

export interface GenerateResult {
  readonly manifest: SurfaceManifest
  readonly jsonPath: string
  readonly tsPath: string
  /** False when the artifacts were already byte-identical. */
  readonly changed: boolean
  readonly json: string
  readonly ts: string
}

/** Render the typed wrapper module for a manifest. */
export function renderManifestModule(manifest: SurfaceManifest): string {
  return `/* eslint-disable */
/**
 * AUTO-GENERATED by packages/surface-registry — DO NOT EDIT.
 *
 * Regenerate: pnpm --filter @ranch/surface-registry generate
 * Drift gate:  pnpm --filter @ranch/surface-registry check
 *
 * Source of truth: the estate SSOTs (config/ports.env, pitchfork.d/*.toml,
 * mise.toml). The numbers below are derived, never hand-written.
 */

import type {
  AgentKind,
  ManifestDaemon,
  ManifestSurface,
  SurfaceManifest,
} from '../manifest'

export const SURFACE_MANIFEST: SurfaceManifest = ${JSON.stringify(manifest, null, 2)}

export function surfaceForAgent(agent: AgentKind): ManifestSurface | null {
  return SURFACE_MANIFEST.surfaces.find((surface) => surface.agent === agent) ?? null
}

export function daemonById(id: string | null): ManifestDaemon | null {
  if (!id) return null
  return SURFACE_MANIFEST.daemons.find((daemon) => daemon.id === id) ?? null
}

export function surfaceAgents(): AgentKind[] {
  return SURFACE_MANIFEST.surfaces.map((surface) => surface.agent).sort()
}
`
}

function readIfExists(path: string): string | null {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return null
  }
}

/** Compose the manifest from the estate SSOTs without writing anything. */
export function deriveManifest(
  estateRoot: string = DEFAULT_ESTATE_ROOT
): SurfaceManifest {
  const sources = readEstateSources(estateRoot)
  return composeManifest({
    sources: sources.sources,
    ports: sources.ports,
    daemons: sources.daemons,
    mise: sources.mise,
    tauRelayUrl: sources.tauRelayUrl,
  })
}

/** Compose the manifest and write the generated artifacts. */
export function generate(options: GenerateOptions = {}): GenerateResult {
  const estateRoot = options.estateRoot ?? DEFAULT_ESTATE_ROOT
  const outDir = options.outDir ?? defaultOutDir()
  const manifest = deriveManifest(estateRoot)

  const json = manifestToJson(manifest)
  const ts = renderManifestModule(manifest)
  const jsonPath = join(outDir, MANIFEST_JSON_NAME)
  const tsPath = join(outDir, MANIFEST_TS_NAME)

  const previousJson = readIfExists(jsonPath)
  const previousTs = readIfExists(tsPath)
  const changed = previousJson !== json || previousTs !== ts

  mkdirSync(outDir, { recursive: true })
  if (previousJson !== json) writeFileSync(jsonPath, json, 'utf8')
  if (previousTs !== ts) writeFileSync(tsPath, ts, 'utf8')

  return { manifest, jsonPath, tsPath, changed, json, ts }
}
