/**
 * gen-facts.ts — regenerate the dynamic FACTS block in README.md from the
 * ACTUAL code (imports the real module, never regex-on-source).
 *
 * Hardcoded counts in prose are a drift bug; this regenerates the single
 * facts block the README includes inside <!-- FACTS:START -->/<!-- FACTS:END -->.
 * Run: `bun run facts` (wired into `bun run build`). tests/facts.test.ts
 * fails the suite if the checked-in block falls behind src/data.ts or the
 * test corpus — the same backstop codegen.test.ts gives generated/.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { PROVIDER_DEFS, MODEL_ALIASES, DEAD_MODEL_IDS } from "../src/data.ts";
import { ADAPTERS } from "../src/adapters.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const readme = join(root, "README.md");

const FACTS_START = "<!-- FACTS:START -->";
const FACTS_END = "<!-- FACTS:END -->";

/** Count test cases across tests/*.test.ts (grep-free, counts `test(`/`it(`). */
function countTests(): number {
  const dir = join(root, "tests");
  let n = 0;
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".test.ts")) continue;
    const src = readFileSync(join(dir, f), "utf8");
    n += (src.match(/\b(?:test|it)\(/g) ?? []).length;
  }
  return n;
}

/** Derive facts purely from live imports — source of truth, not prose. */
export function buildFactsBlock(): string {
  const providers = PROVIDER_DEFS.filter((p) => p.enabled !== false);
  const carriers = PROVIDER_DEFS.filter((p) =>
    Array.isArray((p as { modelProviders?: unknown }).modelProviders),
  );
  const backends = carriers.reduce(
    (n, p) =>
      n + ((p as { modelProviders?: unknown[] }).modelProviders?.length ?? 0),
    0,
  );
  const distinct = new Set<string>();
  for (const def of PROVIDER_DEFS) {
    const mp = (def as { modelProviders?: { name?: string }[] }).modelProviders;
    if (Array.isArray(mp) && mp.length) {
      for (const b of mp) if (b.name) distinct.add(`${def.name}.${b.name}`);
    } else {
      distinct.add(def.name);
    }
  }
  const lines = [
    "<!-- FACTS:START -->",
    "",
    "> **Live facts** (auto-generated by `bun run facts` from `src/data.ts` & the test",
    "> corpus — edit the code, never this block; `tests/facts.test.ts` fails if it",
    "> drifts).",
    "",
    "| Fact | Value |",
    "| --- | --- |",
    `| provider defs | ${PROVIDER_DEFS.length} |`,
    `| enabled providers | ${providers.length} |`,
    `| modelProvider carriers | ${carriers.length} (` +
      `${carriers.map((c) => c.name).join(", ") || "—"}) |`,
    `| serving backends | ${backends} modelProviders, ` +
      `${distinct.size} distinct serve-paths |`,
    `| model aliases | ${Object.keys(MODEL_ALIASES).length} |`,
    `| dead model ids | ${DEAD_MODEL_IDS.length} |`,
    `| endpoint adapters | ${Object.keys(ADAPTERS).length} (` +
      `${Object.keys(ADAPTERS).join(", ")}) |`,
    `| tests | ${countTests()} across tests/*.test.ts |`,
    "",
    "<!-- FACTS:END -->",
  ];
  return lines.join("\n");
}

/** Replace the FACTS block in README.md in place. Returns true if changed. */
export function syncFacts(readmePath = readme): boolean {
  const src = readFileSync(readmePath, "utf8");
  const start = src.indexOf(FACTS_START);
  const end = src.indexOf(FACTS_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `README.md missing FACTS markers (${FACTS_START}…${FACTS_END}) at ${readmePath}`,
    );
  }
  const next = src.slice(0, start) + buildFactsBlock() + src.slice(end + FACTS_END.length);
  if (next === src) return false;
  writeFileSync(readmePath, next, "utf8");
  return true;
}

if (import.meta.main) {
  const changed = syncFacts();
  console.log(changed ? "[facts] README.md FACTS block updated" : "[facts] README.md FACTS block current");
}